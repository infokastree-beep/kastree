_R2_JURISDICTIONS = frozenset({"wnam", "enam", "weur", "eeur", "apac", "oc", "auto"})


def _storage_is_r2() -> bool:
    """Cloudflare R2 does not implement S3 object tagging on PutObject."""
    url = settings.normalized_s3_endpoint_url() or ""
    return "r2.cloudflarestorage.com" in url


def _s3_client_region() -> str:
    """R2 rejects AWS region names (e.g. eu-west-1); use a jurisdiction or auto."""
    if _storage_is_r2():
        if settings.s3_region in _R2_JURISDICTIONS:
            return settings.s3_region
        return "auto"
    return settings.s3_region

