"""Excel / PDF / CSV export generation (Product Spec §4.4, §12.1, §12.2).

Watermarking is derived only from organisations.subscription_tier (== \"free\"),
never from a free-floating boolean. Export files are uploaded under the
exports/ prefix and tagged retention=export-30d. Actual 30-day deletion is a
bucket lifecycle rule configured by backend/scripts/configure_s3_lifecycle.py
(see docs/runbooks/deployment.md) — not put_object(Expires=...), which is only
an HTTP caching hint. Statement data stays in Postgres; regenerate after expiry.
"""

