def export_object_key(export_id: uuid.UUID, format: ExportFormat) -> str:
    return f"{EXPORT_PREFIX}{export_id}.{format}"


def upload_export_file(
    storage: ObjectStorage,
    *,
    export_id: uuid.UUID,
    format: ExportFormat,
    built: BuiltExport,
) -> str:
    """Upload under exports/ and return a signed URL.

    Objects are tagged retention=export-30d so the bucket lifecycle rule from
    backend/scripts/configure_s3_lifecycle.py (docs/runbooks/deployment.md) can
    expire them after export_file_ttl_days. put_object Expires= is only an HTTP
    caching hint — it does not delete objects. Application code regenerates from
    retained statement data if a later download finds the object gone; it does
    not implement its own sweeper.
    """
    key = export_object_key(export_id, format)
    expires_at = datetime.now(timezone.utc) + timedelta(
        days=settings.export_file_ttl_days
    )
    storage.put_export(
        key=key,
        body=built.content,
        content_type=built.content_type,
        expires_at=expires_at,
    )
    return storage.generate_signed_url(
        key=key,
        expires_in=settings.export_signed_url_ttl_seconds,
    )


def mark_export_processing(export: ExportStatusTarget) -> None:
    export.status = "processing"
    export.error_message = None


def mark_export_complete(export: ExportStatusTarget, *, file_url: str) -> None:
    export.status = "complete"
    export.file_url = file_url
    export.error_message = None


def mark_export_failed(export: ExportStatusTarget, *, error_message: str) -> None:
    export.status = "failed"
    export.error_message = error_message


def run_export_job(
    export: ExportStatusTarget,
    *,
    format: ExportFormat,
    branding: ExportBranding,
    package: ExportPackage,
    organisation: OrganisationTier,
    storage: ObjectStorage,
    export_id: uuid.UUID,
) -> ExportStatusTarget:
    """pending → processing → complete|failed, including S3 upload."""
    mark_export_processing(export)
    try:
        built = build_export(
            format,
            branding=branding,
            package=package,
            organisation=organisation,
        )
        file_url = upload_export_file(
            storage,
            export_id=export_id,
            format=format,
            built=built,
        )
        mark_export_complete(export, file_url=file_url)
    except Exception as exc:
        logger.exception("Export job failed for %s", export_id)
        mark_export_failed(export, error_message=str(exc))
    return export


def regenerate_export_if_missing(
    export: ExportStatusTarget,
    *,
    format: ExportFormat,
    branding: ExportBranding,
    package: ExportPackage,
    organisation: OrganisationTier,
    storage: ObjectStorage,
    export_id: uuid.UUID,
) -> str:
    """If the 30-day object is gone, rebuild from retained statement data."""
    key = export_object_key(export_id, format)
    if storage.object_exists(key=key) and export.file_url:
        return storage.generate_signed_url(
            key=key,
            expires_in=settings.export_signed_url_ttl_seconds,
        )
    run_export_job(
        export,
        format=format,
        branding=branding,
        package=package,
        organisation=organisation,
        storage=storage,
        export_id=export_id,
    )
    if export.status != "complete" or not export.file_url:
        raise RuntimeError(export.error_message or "Export regeneration failed")
    return export.file_url


class ExportStatusTarget(Protocol):
    status: str
    file_url: str | None
    error_message: str | None


class S3ObjectStorage:
    """boto3-backed storage for S3 or Cloudflare R2."""

    def __init__(self, client: object | None = None) -> None:
        if client is not None:
            self._client = client
        else:
            import boto3

            kwargs: dict[str, object] = {"region_name": _s3_client_region()}
            endpoint = settings.normalized_s3_endpoint_url()
            if endpoint:
                kwargs["endpoint_url"] = endpoint
            if settings.aws_access_key_id and settings.aws_secret_access_key:
                kwargs["aws_access_key_id"] = settings.aws_access_key_id
                kwargs["aws_secret_access_key"] = settings.aws_secret_access_key
            self._client = boto3.client("s3", **kwargs)

    def put_export(
        self,
        *,
        key: str,
        body: bytes,
        content_type: str,
        expires_at: datetime,
    ) -> None:
        # Expires= → HTTP Expires response header only (caching hint). It does
        # NOT schedule object deletion. Tagging= feeds AWS S3 lifecycle filters;
        # R2 does not support x-amz-tagging on PutObject — use prefix-only
        # lifecycle on R2 (see configure_s3_lifecycle.py).
        put_kwargs: dict[str, object] = {
            "Bucket": settings.s3_bucket,
            "Key": key,
            "Body": body,
            "ContentType": content_type,
            "Expires": expires_at,
            "Metadata": {
                "export-ttl-days": str(settings.export_file_ttl_days),
            },
        }
        if not _storage_is_r2():
            put_kwargs["Tagging"] = "retention=export-30d"
        self._client.put_object(**put_kwargs)

    def generate_signed_url(self, *, key: str, expires_in: int) -> str:
        return self._client.generate_presigned_url(
            "get_object",
            Params={"Bucket": settings.s3_bucket, "Key": key},
            ExpiresIn=expires_in,
        )

    def object_exists(self, *, key: str) -> bool:
        try:
            self._client.head_object(Bucket=settings.s3_bucket, Key=key)
            return True
        except Exception:
            return False


