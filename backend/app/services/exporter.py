def _write_branding(
    ws: Worksheet,
    branding: ExportBranding,
    *,
    watermark: bool,
    start_row: int = 1,
) -> int:
    ws.cell(start_row, 1, branding.client_name).font = _BRAND_FONT
    ws.cell(start_row + 1, 1, f"Period end: {branding.period_end.isoformat()}")
    ws.cell(
        start_row + 2,
        1,
        f"All amounts in {branding.functional_currency.upper()}",
    )
    ws.cell(
        start_row + 3,
        1,
        f"Generated: {branding.generated_at.strftime('%Y-%m-%d %H:%M UTC')}",
    )
    if branding.organisation_name:
        ws.cell(start_row + 4, 1, f"Organisation: {branding.organisation_name}")
        next_row = start_row + 5
    else:
        next_row = start_row + 4
    if watermark:
        cell = ws.cell(next_row, 1, WATERMARK_TEXT)
        cell.font = _WATERMARK_FONT
        next_row += 1
    return next_row + 1


def _write_disclaimer(ws: Worksheet, row: int) -> int:
    cell = ws.cell(row, 1, DISCLAIMER_TEXT)
    cell.font = _DISCLAIMER_FONT
    ws.merge_cells(start_row=row, start_column=1, end_row=row, end_column=4)
    return row + 2


def _write_statement_sheet(
    workbook: Workbook,
    title: str,
    branding: ExportBranding,
    lines: Sequence[StatementLineItemRecord],
    watermark: bool,
) -> None:
    ws = workbook.create_sheet(title)
    row = _write_branding(ws, branding, watermark=watermark)
    row = _write_disclaimer(ws, row)
    ws.cell(row, 1, "Line item").font = _HEADER_FONT
    ws.cell(row, 1).fill = _HEADER_FILL
    ws.cell(row, 2, "Amount").font = _HEADER_FONT
    ws.cell(row, 2).fill = _HEADER_FILL
    ws.cell(row, 3, "Subtotal").font = _HEADER_FONT
    ws.cell(row, 3).fill = _HEADER_FILL
    row += 1
    money_format = _money_number_format(branding.functional_currency)
    for line in lines:
        ws.cell(row, 1, line.line_item_name)
        amount_cell = ws.cell(row, 2, _excel_money(line.amount))
        amount_cell.number_format = money_format
        amount_cell.alignment = Alignment(horizontal="right")
        ws.cell(row, 3, "Yes" if line.is_subtotal else "No")
        row += 1
    _autosize(ws, 3)


def _write_variance_sheet(
    workbook: Workbook,
    branding: ExportBranding,
    variance: VarianceAnalysisResult | None,
    watermark: bool,
) -> None:
    ws = workbook.create_sheet("Variance")
    row = _write_branding(ws, branding, watermark=watermark)
    row = _write_disclaimer(ws, row)
    headers = [
        "Line item",
        "Current",
        "Prior",
        "Variance",
        "Variance %",
        "Direction",
        "Material",
    ]
    for col, header in enumerate(headers, start=1):
        cell = ws.cell(row, col, header)
        cell.font = _HEADER_FONT
        cell.fill = _HEADER_FILL
    row += 1
    money_format = _money_number_format(branding.functional_currency)
    if variance is not None:
        for item in variance.items:
            ws.cell(row, 1, item.line_item_name)
            for col, raw in enumerate(
                (item.current_amount, item.prior_amount, item.variance_amount),
                start=2,
            ):
                cell = ws.cell(row, col, _excel_money(Decimal(raw)))
                cell.number_format = money_format
            ws.cell(
                row,
                5,
                item.variance_pct if item.variance_pct is not None else "",
            )
            ws.cell(row, 6, item.direction)
            ws.cell(row, 7, "Yes" if item.is_material else "No")
            row += 1
    _autosize(ws, 7)


def _write_risk_sheet(
    workbook: Workbook,
    branding: ExportBranding,
    flags: Sequence[RiskFlagRecord],
    watermark: bool,
) -> None:
    ws = workbook.create_sheet("Risk")
    row = _write_branding(ws, branding, watermark=watermark)
    row = _write_disclaimer(ws, row)
    for col, header in enumerate(
        ("Rule", "Severity", "Description", "Recommended action"), start=1
    ):
        cell = ws.cell(row, col, header)
        cell.font = _HEADER_FONT
        cell.fill = _HEADER_FILL
    row += 1
    for flag in flags:
        ws.cell(row, 1, flag.rule_name)
        ws.cell(row, 2, flag.severity)
        ws.cell(row, 3, flag.description)
        ws.cell(row, 4, flag.recommended_action or "")
        row += 1
    _autosize(ws, 4)


def _write_mapping_sheet(
    workbook: Workbook,
    branding: ExportBranding,
    mappings: Sequence[MappingResult],
    watermark: bool,
) -> None:
    ws = workbook.create_sheet("Mapping Summary")
    row = _write_branding(ws, branding, watermark=watermark)
    row = _write_disclaimer(ws, row)
    for col, header in enumerate(
        ("Code", "Name", "Canonical line", "Method", "Confidence"), start=1
    ):
        cell = ws.cell(row, col, header)
        cell.font = _HEADER_FONT
        cell.fill = _HEADER_FILL
    row += 1
    for mapping in mappings:
        ws.cell(row, 1, mapping.source_code)
        ws.cell(row, 2, mapping.source_name)
        ws.cell(row, 3, mapping.canonical_line or "")
        ws.cell(row, 4, mapping.method or "")
        if mapping.confidence is not None:
            cell = ws.cell(row, 5, _excel_money(mapping.confidence))
            cell.number_format = "0.00"
        else:
            ws.cell(row, 5, "")
        row += 1
    _autosize(ws, 5)


def _excel_money(amount: Decimal) -> Decimal:
    """Quantize for the sheet — returns Decimal, never float."""
    if not isinstance(amount, Decimal):
        raise TypeError(f"Excel money cells require Decimal, got {type(amount)!r}")
    return amount.quantize(Decimal("0.01"))


def _money_str(amount: Decimal) -> str:
    return f"{amount.quantize(Decimal('0.01'))}"


def _autosize(ws: Worksheet, columns: int) -> None:
    for index in range(1, columns + 1):
        letter = get_column_letter(index)
        max_length = 0
        for cell in ws[letter]:
            value = "" if cell.value is None else str(cell.value)
            max_length = max(max_length, len(value))
        ws.column_dimensions[letter].width = min(max_length + 2, 60)


def _filename(branding: ExportBranding, extension: str) -> str:
    safe = "".join(
        ch if ch.isalnum() or ch in ("-", "_") else "_"
        for ch in branding.client_name.strip()
    ) or "export"
    return f"{safe}_{branding.period_end.isoformat()}.{extension}"


def _html_escape(value: str) -> str:
    return (
        value.replace("&", "&amp;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
        .replace('"', "&quot;")
    )
